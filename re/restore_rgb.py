import hid, time

VID, PID = 0x1EA7, 0x9018
path = None
for info in hid.enumerate(VID, PID):
    if info['usage_page'] == 0xFF01 and info['usage'] == 0x0001:
        path = info['path']
d = hid.device(); d.open_path(path); d.set_nonblocking(1)

def send(buf):
    d.send_feature_report([0x07] + list(buf))
    time.sleep(0.15)

def recv():
    time.sleep(0.05)
    return list(d.get_feature_report(0x07, 264))

# ---- read current (shifted) block ----
send([0x82, 1, 0, 0, 0, 0, 0] + [0] * 257)
R = recv()
S = R[8:264]                      # current stored block (256 bytes)
print("current head:", " ".join(f"{b:02x}" for b in R[:24]))

# ---- un-shift: S_new[i] = S_orig[i-1]  =>  S_orig[j] = S_cur[j+1] ----
payload = [S[i + 1] for i in range(255)] + [0x00]   # S_orig[255] was 0x00 (from original dump)
send([0x02, 1, 0, 0, 0, 0, 0] + payload)
time.sleep(0.4)

# ---- verify against the original dump captured before the test ----
send([0x82, 1, 0, 0, 0, 0, 0] + [0] * 257)
R2 = recv()

EXPECTED = (
    [0x07,0x82,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x06,0x00,0x00,0x00] +
    [0x00,0x00,0x00,0x34,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00] +
    [0x00] * 48 +
    [0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0xad,0xa3,0x99,0x9e] +
    [0x00,0xf4,0xf6,0xee,0xb8,0xb0,0x99,0xf9,0xca,0xe2,0xcd,0xa9,0x8a,0xa0,0xff,0x90] +
    [0x83,0x68,0xcc,0x80,0xda,0x80,0x7a,0x8a,0xff,0xff,0xff,0xff,0xff,0xef,0xeb,0xee] +
    [0xff,0xff,0xff,0xff,0xff,0xff,0x00,0x00,0x02,0x00,0x00,0x00,0x00,0x00,0x00,0x00] +
    [0x00] * (264 - 144)
)

mismatch = [(i, EXPECTED[i], R2[i]) for i in range(264) if EXPECTED[i] != R2[i]]
if not mismatch:
    print("VERIFIED: block is byte-identical to the original read. RGB settings fully restored.")
else:
    print(f"{len(mismatch)} mismatches vs original:")
    for i, e, a in mismatch[:20]:
        print(f"  resp[{i}]: expected 0x{e:02x} got 0x{a:02x}")

d.close()
