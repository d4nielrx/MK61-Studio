import hid, time

VID, PID = 0x1EA7, 0x9018
path = None
for info in hid.enumerate(VID, PID):
    if info['usage_page'] == 0xFF01 and info['usage'] == 0x0001:
        path = info['path']
d = hid.device(); d.open_path(path); d.set_nonblocking(1)

def send(buf):
    d.send_feature_report([0x07] + list(buf))
    time.sleep(0.15)

def recv():
    time.sleep(0.05)
    return list(d.get_feature_report(0x07, 264))

# Verbatim original response dump (resp[0..263]), captured by validate_protocol.py
# BEFORE any write tests. Kept as raw rows to avoid any index conversion mistakes.
ROWS = [
    [0x07,0x82,0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x06,0x00,0x00,0x00],
    [0x00,0x00,0x00,0x34,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00],
    [0x00]*16, [0x00]*16, [0x00]*16,
    [0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0xad,0xa3,0x99,0x9e],
    [0x00,0xf4,0xf6,0xee,0xb8,0xb0,0x99,0xf9,0xca,0xe2,0xcd,0xa9,0x8a,0xa0,0xff,0x90],
    [0x83,0x68,0xcc,0x80,0xda,0x80,0x7a,0x8a,0xff,0xff,0xff,0xff,0xff,0xef,0xeb,0xee],
    [0xff,0xff,0xff,0xff,0xff,0xff,0x00,0x00,0x02,0x00,0x00,0x00,0x00,0x00,0x00,0x00],
    [0x00]*16, [0x00]*16, [0x00]*16, [0x00]*16, [0x00]*16, [0x00]*16, [0x00]*16,
    [0x00]*8,
]
RESP = [b for row in ROWS for b in row]
assert len(RESP) == 264, len(RESP)

block = RESP[8:264]          # 256-byte settings block, sliced programmatically
assert len(block) == 256

# Identity write: Data[8+i] = block[i]  (verified mapping)
send([0x02, 1, 0, 0, 0, 0, 0] + block)
time.sleep(0.4)

# Verify — tolerate the firmware-managed status bytes (block[129..133], block[136])
send([0x82, 1, 0, 0, 0, 0, 0] + [0] * 257)
R = recv()
deviceManaged = set(range(129, 134)) | {136}
bad = [(i, block[i], R[8 + i]) for i in range(256)
       if R[8 + i] != block[i] and i not in deviceManaged]
if not bad:
    print("RESTORED: all user settings (effect/brightness/colors) byte-identical to original.")
else:
    print(f"{len(bad)} unexpected mismatches:")
    for i, e, a in bad[:20]:
        print(f"  block[{i}]: expected 0x{e:02x} got 0x{a:02x}")

d.close()
